const SEGMENTS = APP_ROUTES.map(route => route.split("/").filter(Boolean));
const isParam = (segment: string): boolean => segment.startsWith("[");

/** The names of the dynamic segments of the page at `pathname`; null when the App has no such page. */
export function appRouteParams(pathname: string): string[] | null {
  const parts = pathname.split("/").filter(Boolean);
  let best: string[] | null = null;
  for (const route of SEGMENTS) {
    if (route.length !== parts.length || !route.every((segment, index) => isParam(segment) || segment === parts[index])) continue;
    // A page written out wins over a dynamic one (`/contacts/new` over `/contacts/[id]`), as in expo-router.
    if (!best || best.length > route.filter(isParam).length) best = route.filter(isParam).map(segment => segment.slice(1, -1));
  }
  return best;
}
