const fs = require("fs");
const path = require("path");
const {
  IOSConfig,
  withAppDelegate,
  withDangerousMod,
  withInfoPlist,
  withXcodeProject
} = require("expo/config-plugins");

// iOS 27 terminates apps that have not adopted the UIScene lifecycle at launch
// (UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption). Expo 57 / RN 0.86
// templates still create the window in the AppDelegate, so the window moves to a SceneDelegate.

const SCENE_DELEGATE_FILE = "SceneDelegate.swift";

const SCENE_MANIFEST = {
  UIApplicationSupportsMultipleScenes: false,
  UISceneConfigurations: {
    UIWindowSceneSessionRoleApplication: [
      {
        UISceneConfigurationName: "Default Configuration",
        UISceneDelegateClassName: "$(PRODUCT_MODULE_NAME).SceneDelegate"
      }
    ]
  }
};

const SCENE_DELEGATE_SOURCE = `import React
import UIKit

// Generated by plugins/with-ios-scene-lifecycle.js. The AppDelegate builds the React Native
// factory; this delegate owns the window and forwards URLs to the AppDelegate handlers.
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard
      let windowScene = scene as? UIWindowScene,
      let appDelegate = UIApplication.shared.delegate as? AppDelegate,
      let factory = appDelegate.reactNativeFactory
    else { return }

    let window = UIWindow(windowScene: windowScene)
    self.window = window
    appDelegate.window = window

    // Cold-start links arrive here instead of didFinishLaunching; Linking.getInitialURL reads these keys.
    var launchOptions: [UIApplication.LaunchOptionsKey: Any] = [:]
    if let url = connectionOptions.urlContexts.first?.url {
      launchOptions[.url] = url
    }
    if let activity = connectionOptions.userActivities.first {
      launchOptions[.userActivityDictionary] = [
        "UIApplicationLaunchOptionsUserActivityKey": activity,
        UIApplication.LaunchOptionsKey.userActivityType.rawValue: activity.activityType
      ]
    }

    factory.startReactNative(withModuleName: "main", in: window, launchOptions: launchOptions)
  }

  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    for context in URLContexts {
      _ = UIApplication.shared.delegate?.application?(UIApplication.shared, open: context.url, options: [:])
    }
  }

  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    _ = UIApplication.shared.delegate?.application?(
      UIApplication.shared,
      continue: userActivity,
      restorationHandler: { _ in }
    )
  }
}
`;

const WINDOW_BLOCK =
  /\n#if os\(iOS\) \|\| os\(tvOS\)\n[ \t]*window = UIWindow\(frame: UIScreen\.main\.bounds\)\n[ \t]*factory\.startReactNative\(\n[^)]*\)\n#endif\n/u;

function rewriteAppDelegate(contents) {
  if (contents.includes("SceneDelegate starts React Native")) return contents;
  if (!WINDOW_BLOCK.test(contents)) {
    throw new Error("Orbit AppDelegate has no template window block to move into SceneDelegate");
  }
  return contents.replace(WINDOW_BLOCK, "\n    // SceneDelegate starts React Native once the window scene connects (iOS 27 UIScene lifecycle).\n");
}

function withIosSceneLifecycle(config) {
  config = withInfoPlist(config, (mod) => {
    mod.modResults.UIApplicationSceneManifest = SCENE_MANIFEST;
    return mod;
  });

  config = withAppDelegate(config, (mod) => {
    if (mod.modResults.language !== "swift") {
      throw new Error("with-ios-scene-lifecycle expects a Swift AppDelegate");
    }
    mod.modResults.contents = rewriteAppDelegate(mod.modResults.contents);
    return mod;
  });

  config = withDangerousMod(config, [
    "ios",
    async (mod) => {
      const projectName = IOSConfig.XcodeUtils.getProjectName(mod.modRequest.projectRoot);
      const target = path.join(mod.modRequest.platformProjectRoot, projectName, SCENE_DELEGATE_FILE);
      fs.writeFileSync(target, SCENE_DELEGATE_SOURCE);
      return mod;
    }
  ]);

  return withXcodeProject(config, (mod) => {
    const projectName = IOSConfig.XcodeUtils.getProjectName(mod.modRequest.projectRoot);
    const filepath = `${projectName}/${SCENE_DELEGATE_FILE}`;
    if (!mod.modResults.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
        filepath,
        groupName: projectName,
        project: mod.modResults
      });
    }
    return mod;
  });
}

module.exports = withIosSceneLifecycle;
module.exports.rewriteAppDelegate = rewriteAppDelegate;
module.exports.SCENE_MANIFEST = SCENE_MANIFEST;
