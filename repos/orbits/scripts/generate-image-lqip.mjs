import { readdir, readFile, writeFile } from "node:fs/promises";
import { extname, join, relative, sep } from "node:path";

import sharp from "sharp";

const projectRoot = process.cwd();
const publicRoot = join(projectRoot, "public");
const sourceDirectories = [
  join(publicRoot, "orbit-covers"),
  join(publicRoot, "orbit-demo-assets"),
];
const outputPath = join(
  projectRoot,
  "shared/ui/orbit-image-lqip.generated.ts",
);
const supportedExtensions = new Set([".avif", ".jpeg", ".jpg", ".png", ".svg", ".webp"]);

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map(async (entry) => {
      const path = join(directory, entry.name);
      return entry.isDirectory() ? walk(path) : [path];
    }),
  );

  return nested.flat();
}

async function makeLqip(path) {
  const buffer = await sharp(path)
    .resize({ fit: "inside", width: 32, withoutEnlargement: true })
    .webp({ effort: 4, quality: 34 })
    .toBuffer();

  return `data:image/webp;base64,${buffer.toString("base64")}`;
}

const files = (
  await Promise.all(sourceDirectories.map((directory) => walk(directory)))
)
  .flat()
  .filter((path) => supportedExtensions.has(extname(path).toLowerCase()))
  .sort((left, right) => left.localeCompare(right));

const entries = await Promise.all(
  files.map(async (path) => {
    const publicPath = `/${relative(publicRoot, path).split(sep).join("/")}`;
    return [publicPath, await makeLqip(path)];
  }),
);
const lqipBySrc = Object.fromEntries(entries);
const output = `// Generated by npm run images:lqip. Do not edit by hand.\n\nexport const ORBIT_IMAGE_LQIP: Readonly<Record<string, string>> = ${JSON.stringify(lqipBySrc, null, 2)};\n\nexport function orbitImageLqip(src: string): string | undefined {\n  return ORBIT_IMAGE_LQIP[src];\n}\n`;

let previous = "";
try {
  previous = await readFile(outputPath, "utf8");
} catch {
  // First generation creates the file.
}

if (previous !== output) {
  await writeFile(outputPath, output, "utf8");
}

console.log(`Generated ${entries.length} inline LQIP entries.`);
