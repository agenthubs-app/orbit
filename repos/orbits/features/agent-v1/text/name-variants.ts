/** The other spellings of `words` (at most `max`, the typed one excluded), each character swapped for its variants. */
export function variantSpellings(words: string, max = 6): string[] {
  let spellings = [""];
  for (const ch of [...words]) {
    const options = MEMBERS.get(ch) ?? [ch];
    const next: string[] = [];
    for (const prefix of spellings) for (const option of options) if (next.length < 64) next.push(prefix + option);
    spellings = next;
  }
  return spellings.filter((spelling) => spelling !== words).slice(0, max);
}
